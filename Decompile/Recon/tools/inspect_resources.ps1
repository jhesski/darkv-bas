# Inspects DV1 resource files in /org/ and reports the structure of each format.
# Output: prints a per-format table to stdout and optionally writes a summary.
param(
  [string]$OrgPath = "C:\Code\darkv-bas\org",
  [string]$OutPath = "C:\Code\darkv-bas\Decompile\Recon\RESOURCES.md"
)

function Inspect-Pac {
  param([string]$Path)
  $lines = Get-Content $Path
  $header = $lines[0]
  $entries = 0
  $zeros = 0
  $allValid = $true
  for ($i = 1; $i -lt $lines.Count; $i++) {
    $l = $lines[$i].Trim()
    if ($l -eq '') { continue }
    $parts = $l.Split(',')
    if ($parts.Count -ne 3) { $allValid = $false; continue }
    if ($parts[0].Trim() -eq '0' -and $parts[1].Trim() -eq '0' -and $parts[2].Trim() -eq '0') {
      $zeros++
    } else {
      $entries++
    }
  }
  [PSCustomObject]@{
    Name = (Split-Path $Path -Leaf)
    Bytes = (Get-Item $Path).Length
    Header = $header
    Entries = $entries
    ZeroPadding = $zeros
    LinesValid = $allValid
  }
}

function Inspect-Pct {
  param([string]$Path)
  $lines = Get-Content $Path
  $rows = 0
  $bad = 0
  $minVal = [int]::MaxValue
  $maxVal = [int]::MinValue
  foreach ($l in $lines) {
    $l = $l.Trim()
    if ($l -eq '') { continue }
    $parts = $l.Split(',')
    if ($parts.Count -eq 4) {
      $rows++
      foreach ($p in $parts) {
        $v = 0
        if ([int]::TryParse($p.Trim(), [ref]$v)) {
          if ($v -lt $minVal) { $minVal = $v }
          if ($v -gt $maxVal) { $maxVal = $v }
        }
      }
    } else { $bad++ }
  }
  [PSCustomObject]@{
    Name = (Split-Path $Path -Leaf)
    Bytes = (Get-Item $Path).Length
    Rows = $rows
    Malformed = $bad
    MinValue = if ($minVal -eq [int]::MaxValue) { 'n/a' } else { $minVal }
    MaxValue = if ($maxVal -eq [int]::MinValue) { 'n/a' } else { $maxVal }
  }
}

function Inspect-Pic {
  param([string]$Path)
  $bytes = [System.IO.File]::ReadAllBytes($Path)
  # BSAVE header: 0xFD + 2-byte segment + 2-byte offset + 2-byte length + data + 0x1A trailer
  $magic = '0x{0:X2}' -f $bytes[0]
  $segment = ([int]$bytes[1]) -bor (([int]$bytes[2]) -shl 8)
  $offset = ([int]$bytes[3]) -bor (([int]$bytes[4]) -shl 8)
  $length = ([int]$bytes[5]) -bor (([int]$bytes[6]) -shl 8)
  [PSCustomObject]@{
    Name = (Split-Path $Path -Leaf)
    Bytes = $bytes.Length
    Magic = $magic
    Segment = ('0x{0:X4}' -f $segment)
    Offset = ('0x{0:X4}' -f $offset)
    PayloadLength = $length
    Trailer = ('0x{0:X2}' -f $bytes[$bytes.Length - 1])
  }
}

$pacFiles = Get-ChildItem $OrgPath -Filter '*.PAC' -File
$pctFiles = Get-ChildItem $OrgPath -Filter '*.PCT' -File
$picFiles = Get-ChildItem $OrgPath -Filter '*.PIC' -File

$pacResults = foreach ($f in $pacFiles) { Inspect-Pac -Path $f.FullName }
$pctResults = foreach ($f in $pctFiles) { Inspect-Pct -Path $f.FullName }
$picResults = foreach ($f in $picFiles) { Inspect-Pic -Path $f.FullName }

# Console output
"== .PAC files ($($pacFiles.Count)) =="
$pacResults | Format-Table -AutoSize
"== .PCT files ($($pctFiles.Count)) =="
$pctResults | Format-Table -AutoSize
"== .PIC files ($($picFiles.Count)) =="
$picResults | Format-Table -AutoSize | Out-String -Width 200

