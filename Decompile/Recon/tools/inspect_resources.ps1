  [void]$sb.AppendLine("| $($r.Name) | $($r.Bytes) | $($r.Rows) | $($r.Malformed) | $($r.MinValue) | $($r.MaxValue) |")
}
[void]$sb.AppendLine()
[void]$sb.AppendLine('## .PIC files (' + $picFiles.Count + ')')
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Name | Bytes | Magic | Segment | Offset | Payload | Trailer |')
[void]$sb.AppendLine('|------|-------|-------|---------|--------|---------|---------|')
foreach ($r in $picResults) {
  [void]$sb.AppendLine("| $($r.Name) | $($r.Bytes) | $($r.Magic) | $($r.Segment) | $($r.Offset) | $($r.PayloadLength) | $($r.Trailer) |")
}

